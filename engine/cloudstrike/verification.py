from __future__ import annotations

import hashlib
import json
from dataclasses import dataclass
from pathlib import Path
from typing import Any


class ReportVerificationError(ValueError):
    """Raised when a CloudStrike report fails the local evidence contract."""


@dataclass(frozen=True)
class VerificationResult:
    path: Path
    digest: str
    lab_id: str
    path_length: int
    detections: int
    blocked_at_step: int | None


def verify_report_file(path: str | Path) -> VerificationResult:
    report_path = Path(path)
    raw = report_path.read_bytes()
    try:
        report = json.loads(raw)
    except json.JSONDecodeError as exc:
        raise ReportVerificationError(f"invalid JSON: {exc.msg}") from exc
    verify_report(report)
    summary = report["summary"]
    return VerificationResult(
        path=report_path,
        digest=hashlib.sha256(raw).hexdigest(),
        lab_id=report["lab_id"],
        path_length=summary["path_length"],
        detections=summary["detections_triggered"],
        blocked_at_step=summary["blocked_at_step"],
    )


def verify_report(report: Any) -> None:
    if not isinstance(report, dict):
        raise ReportVerificationError("report must be a JSON object")

    _require(report.get("schema_version") == "1.0", "unsupported report schema")
    lab_id = _require_str(report, "lab_id")
    _require(lab_id.startswith("cloudstrike-lab-"), "report is not scoped to a CloudStrike lab")
    _verify_provenance(_require_dict(report, "provenance"))
    _verify_inventory(_require_dict(report, "inventory"), lab_id)

    attack_path = _require_dict(report, "attack_path")
    steps = _require_list(attack_path, "steps")
    path_nodes = _require_list(attack_path, "nodes")
    _require(len(path_nodes) == len(steps) + 1, "attack-path node/edge counts are inconsistent")
    _require(attack_path.get("length") == len(steps), "attack-path length is inconsistent")
    _verify_path_is_in_inventory(report["inventory"], path_nodes, steps)

    before = _require_dict(report, "before")
    after = _require_dict(report, "after")
    _verify_replay(before, lab_id, "before")
    _verify_replay(after, lab_id, "after")
    _verify_summary(_require_dict(report, "summary"), before, after, len(steps), report)
    _verify_detections(_require_list(report, "detections"), before, lab_id)
    _verify_remediation(_require_dict(report, "remediation"))


def _verify_provenance(provenance: dict[str, Any]) -> None:
    _require(
        provenance.get("generator") == "cloudstrike-engine",
        "report was not generated by the CloudStrike engine",
    )
    _require(
        provenance.get("mode") == "controlled-local-simulation",
        "report was not produced by the controlled local simulator",
    )
    _require(provenance.get("live_aws_actions") == 0, "report contains live AWS actions")
    _require_str(provenance, "fixture")


def _verify_inventory(inventory: dict[str, Any], lab_id: str) -> None:
    _require(inventory.get("lab_id") == lab_id, "inventory lab_id does not match report lab_id")
    nodes = _require_list(inventory, "nodes")
    edges = _require_list(inventory, "edges")
    _require(nodes, "inventory has no nodes")
    _require(edges, "inventory has no edges")
    for node in nodes:
        node_obj = _as_dict(node, "inventory node")
        _require_str(node_obj, "id")
        _require_str(node_obj, "kind")
        _require_str(node_obj, "name")
    for edge in edges:
        edge_obj = _as_dict(edge, "inventory edge")
        _require_str(edge_obj, "source")
        _require_str(edge_obj, "target")
        _require_str(edge_obj, "relation")


def _verify_path_is_in_inventory(
    inventory: dict[str, Any], path_nodes: list[Any], steps: list[Any]
) -> None:
    inventory_nodes = {_as_dict(node, "inventory node")["id"] for node in inventory["nodes"]}
    inventory_edges = set()
    for edge in inventory["edges"]:
        edge_obj = _as_dict(edge, "inventory edge")
        inventory_edges.add((edge_obj["source"], edge_obj["relation"], edge_obj["target"]))
    for node in path_nodes:
        _require(isinstance(node, str), "attack-path node ids must be strings")
        _require(node in inventory_nodes, f"attack-path node is absent from inventory: {node}")
    for index, step in enumerate(steps):
        step_obj = _as_dict(step, "attack-path step")
        source = _require_str(step_obj, "source")
        relation = _require_str(step_obj, "relation")
        target = _require_str(step_obj, "target")
        _require(path_nodes[index] == source, f"step {index + 1} source does not match path nodes")
        _require(path_nodes[index + 1] == target, f"step {index + 1} target does not match path nodes")
        _require(
            (source, relation, target) in inventory_edges,
            f"step {index + 1} is absent from inventory edges",
        )


def _verify_replay(replay: dict[str, Any], lab_id: str, label: str) -> None:
    status = _require_str(replay, "status")
    _require(status in {"SUCCESS", "BLOCKED"}, f"{label} replay has invalid status")
    events = _require_list(replay, "events")
    if status == "SUCCESS":
        _require(replay.get("stopped_at") is None, f"{label} replay success cannot have stopped_at")
        _require(replay.get("reason") is None, f"{label} replay success cannot have reason")
    if status == "BLOCKED":
        _require(isinstance(replay.get("stopped_at"), int), f"{label} replay is missing stopped_at")
        _require(isinstance(replay.get("reason"), str), f"{label} replay is missing reason")
    for event in events:
        event_obj = _as_dict(event, f"{label} event")
        _require(event_obj.get("lab_id") == lab_id, f"{label} event lab_id does not match")
        _require_str(event_obj, "event_name")
        _require_str(event_obj, "actor")
        _require_str(event_obj, "target")
        _require(isinstance(event_obj.get("allowed"), bool), f"{label} event allowed must be boolean")


def _verify_summary(
    summary: dict[str, Any],
    before: dict[str, Any],
    after: dict[str, Any],
    path_length: int,
    report: dict[str, Any],
) -> None:
    _require(summary.get("before") == before["status"], "summary before status does not match replay")
    _require(summary.get("after") == after["status"], "summary after status does not match replay")
    _require(summary.get("path_length") == path_length, "summary path_length is inconsistent")
    _require(
        summary.get("detections_triggered") == len(report["detections"]),
        "summary detection count is inconsistent",
    )
    _require(
        summary.get("blocked_at_step") == after.get("stopped_at"),
        "summary blocked_at_step does not match remediated replay",
    )
    _require(
        summary.get("blocked_reason") == after.get("reason"),
        "summary blocked_reason does not match remediated replay",
    )


def _verify_detections(detections: list[Any], before: dict[str, Any], lab_id: str) -> None:
    before_events = set()
    for event in before["events"]:
        event_obj = _as_dict(event, "before event")
        before_events.add((event_obj["event_name"], event_obj["target"]))
    for detection in detections:
        detection_obj = _as_dict(detection, "detection")
        _require_str(detection_obj, "rule_id")
        _require_str(detection_obj, "title")
        _require_str(detection_obj, "severity")
        _require_list(detection_obj, "mitre_techniques")
        event = _require_dict(detection_obj, "event")
        _require(event.get("lab_id") == lab_id, "detection event lab_id does not match")
        event_key = (_require_str(event, "event_name"), _require_str(event, "target"))
        _require(event_key in before_events, "detection event is not present in vulnerable replay")


def _verify_remediation(remediation: dict[str, Any]) -> None:
    _require_str(remediation, "finding")
    _require_str(remediation, "replacement")
    _require_str(remediation, "terraform_file")
    remove_actions = _require_list(remediation, "remove_actions")
    _require(remove_actions, "remediation must remove at least one action")
    _require(
        all(isinstance(action, str) and action for action in remove_actions),
        "remediation remove_actions must be non-empty strings",
    )


def _require(condition: bool, message: str) -> None:
    if not condition:
        raise ReportVerificationError(message)


def _require_dict(parent: dict[str, Any], key: str) -> dict[str, Any]:
    value = parent.get(key)
    if not isinstance(value, dict):
        raise ReportVerificationError(f"{key} must be an object")
    return value


def _require_list(parent: dict[str, Any], key: str) -> list[Any]:
    value = parent.get(key)
    if not isinstance(value, list):
        raise ReportVerificationError(f"{key} must be a list")
    return value


def _require_str(parent: dict[str, Any], key: str) -> str:
    value = parent.get(key)
    if not isinstance(value, str) or not value:
        raise ReportVerificationError(f"{key} must be a non-empty string")
    return value


def _as_dict(value: Any, label: str) -> dict[str, Any]:
    if not isinstance(value, dict):
        raise ReportVerificationError(f"{label} must be an object")
    return value
